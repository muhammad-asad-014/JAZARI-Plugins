@bp.route('/ai-recognize', methods=['POST'])
def ai_recognize():
    data = request.get_json()
    image_data = data.get('image') 
    class_id = data.get('class_id')
    from core.models import Student
    students = Student.query.filter_by(classID=class_id).all()

    embeddings = []

    for student in students:
        embeddings.append(json.loads(student.embedding))

    from utils.utilities import find_faces
    try:
        img = decode_base64_image(image_data)
        res = {}
        for st in students:
            res[st.id] = 'absent'
        faces = find_faces(img, embeddings)
        for face in faces:
            res[face] = 'present'
        return jsonify({
            "success": True,
            "attendance": res
        })
    except Exception as e:
        print(e)
    
    return None




def decode_base64_image(image_data):
    if "," in image_data:
        header, encoded = image_data.split(",", 1)
    else:
        encoded = image_data

    decoded_bytes = base64.b64decode(encoded)

    nparr = np.frombuffer(decoded_bytes, np.uint8)
    opencv_img = cv2.imdecode(nparr, cv2.IMREAD_COLOR)

    return opencv_img



@bp.route('/delete/<report_id>/')
@teacher_only
def delete_report(report_id):
    from core.models import Attendance
    report = Attendance.query.filter_by(id=report_id).first()

    if not report:
        flash("Error: Report no longer exists.", "error")
        return redirect(url_for('aero.home'))

    try:
        filename = f"{report_id}.pdf"
        file_path = os.path.join(attendance_folder, filename)
        
        if os.path.exists(file_path):
            os.remove(file_path)
            print(f"File {filename} deleted from storage.")
        else:
            print(f"Note: File {filename} was already missing from storage.")

        db.session.delete(report)
        db.session.commit()

        flash(f"Report {report_id} has been permanently deleted.", "success")

    except Exception as e:
        db.session.rollback() 
        print(f"Delete Error: {e}")
        flash(f"An error occurred while deleting: {str(e)}", "error")

    return redirect(url_for('aero.home'))
