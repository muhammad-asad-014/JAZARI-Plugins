def generate_quiz_report(quiz_id):
    print('generating report ..')
    table_name = f"temp_{quiz_id}"
    results = db.session.execute(text(f"SELECT * FROM {table_name}")).fetchall()
    if not results:
        return False, "No data found."

    print(results)

    scores = [r.obtained_marks for r in results]
    names = [r.student_name for r in results]
    avg_score = sum(scores) / len(results)
    max_score, min_score = max(scores), min(scores)
    
    top_scorer = ", ".join([r.student_name for r in results if r.obtained_marks == max_score])
    lowest_scorer = ", ".join([r.student_name for r in results if r.obtained_marks == min_score])

    today = date.today() # [cite: 5]
    filename = f"{quiz_id}.pdf"
    full_path = os.path.join(records_folder, filename)
    
    doc = SimpleDocTemplate(full_path, pagesize=letter, rightMargin=30, leftMargin=30, topMargin=30, bottomMargin=18)
    styles = getSampleStyleSheet()
    elements = []

    title_style = ParagraphStyle('TitleStyle', parent=styles['Heading1'], alignment=1, fontSize=18, spaceAfter=2)
    sub_title_style = ParagraphStyle('SubTitle', parent=styles['Normal'], alignment=1, fontSize=10, bold=True)
    
    from core.models import Settings
    settings = Settings.query.get('001')
    elements.append(Paragraph(settings.orgName, title_style)) 
    elements.append(Paragraph("Automated report generated by JAZARI", sub_title_style))
    elements.append(Paragraph(f"Quiz Assessment Report - {today.strftime('%B %Y')}", sub_title_style))
    elements.append(Spacer(1, 0.2 * inch))

    details_data = [
        [f"Quiz ID: {quiz_id}"],
        [f"Report ID: {quiz_id}.pdf", f"Date: {today}"]
    ]
    details_table = Table(details_data, colWidths=[4*inch, 2.5*inch])
    details_table.setStyle(TableStyle([
        ('FONTNAME', (0,0), (-1,-1), 'Helvetica-Bold'),
        ('FONTSIZE', (0,0), (-1,-1), 9),
        ('ALIGN', (0,0), (-1,-1), 'LEFT'),
    ]))
    elements.append(details_table)
    elements.append(Spacer(1, 0.2 * inch))

    elements.append(Paragraph("Score Distribution Chart", styles['Heading3']))
    drawing = Drawing(400, 200)
    bc = VerticalBarChart()
    bc.x = 50
    bc.y = 50
    bc.height = 125
    bc.width = 300
    bc.data = [scores]
    bc.categoryAxis.categoryNames = names
    bc.valueAxis.valueMin = 0
    bc.valueAxis.valueMax = results[0].total_marks # Scale to total possible marks
    bc.valueAxis.valueStep = 1
    bc.barSpacing = 2
    drawing.add(bc)
    elements.append(drawing)
    elements.append(Spacer(1, 0.2 * inch))

    summary_data = [
        ["Metric", "Value"],
        ["Average Score", f"{avg_score:.2f}"],
        ["Top Scorer(s)", f"{top_scorer} ({max_score})"],
        ["Lowest Scorer(s)", f"{lowest_scorer} ({min_score})"]
    ]
    summary_table = Table(summary_data, colWidths=[2*inch, 4.5*inch])
    summary_table.setStyle(TableStyle([
        ('GRID', (0,0), (-1,-1), 0.5, colors.black),
        ('BACKGROUND', (0,0), (-1,0), colors.whitesmoke),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('TEXTCOLOR', (0,1), (0, -1), colors.darkblue),
    ]))
    elements.append(summary_table)
    elements.append(Spacer(1, 0.3 * inch))

    data = [["Sr#", "Student ID", "Name", "Score"]]
    for i, r in enumerate(results, 1):
        data.append([i, r.student_id, r.student_name, r.obtained_marks])

    res_table = Table(data, colWidths=[0.5*inch, 1.5*inch, 3*inch, 1.5*inch])
    res_table.setStyle(TableStyle([
        ('GRID', (0,0), (-1,-1), 0.5, colors.black),
        ('BACKGROUND', (0,0), (-1,0), colors.whitesmoke),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('ALIGN', (0,0), (1,-1), 'CENTER'),
        ('ALIGN', (3,0), (3,-1), 'CENTER'),
    ]))
    elements.append(res_table)

    doc.build(elements)
    return True, full_path

