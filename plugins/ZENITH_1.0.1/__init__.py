@bp.route('/end-quiz', methods=['POST'])
def end_quiz():

    data = request.get_json()

    quiz_id = data.get('quiz_id')

    from core.models import Quiz

    if not quiz_id:
        return jsonify({"status": "error", "message": "Missing Quiz ID"}), 400

    try:
        generate_quiz_report(quiz_id)
        Quiz.query.filter_by(id=quiz_id).update({"status": "ended"})
        db.session.commit()
        table_name = f"temp_{quiz_id}"
        drop_query = text(f"DROP TABLE IF EXISTS {table_name}")
        db.session.execute(drop_query)
        db.session.commit()

        return jsonify({
            "status": "success", 
            "message": f"Quiz {quiz_id} set to ended and {table_name} removed."
        }), 200

    except Exception as e:
        db.session.rollback()
        print(f"Error: {e}")
        return jsonify({"status": "error", "message": str(e)}), 500


