def generate_quiz(app, id, data, name, teacher, classID, pdf_path, topics, count, difficulty, status):
    with app.app_context():
        from core.models import Quiz
        from sqlalchemy import text
        
        try:
            socketio.emit('quiz_progress', {'percentage': 10, 'message': 'Extracting data...', 'status': 'processing'})
            print('='*20)
            print(data)
            print(data['OPENROUTER_API_KEY'])
            from utils.utilities import quiz_generator
            generated_quiz = quiz_generator(api_key=data['OPENROUTER_API_KEY'], model=data['MODEL'], difficulty=difficulty, count=count, quiz_topics=topics, quiz_doc=pdf_path)
            
            socketio.emit('quiz_progress', {'percentage': 50, 'message': 'AI generating questions...', 'status': 'processing'})
            
            if not generated_quiz or generated_quiz.get('redflag'):
                raise Exception("AI flagged the content or failed to generate.")

            time.sleep(2) 
            socketio.emit('quiz_progress', {'percentage': 80, 'message': 'Saving to database...', 'status': 'processing'})
            
            quiz = Quiz.query.get(id)
            if not quiz:
                raise Exception("Quiz record lost during processing.")
                
            quiz.status = 'active'
            quiz.embedding = generated_quiz['quiz_JSON']
            db.session.commit()
            
            table_name = f"temp_{id}"
            query = text(f"""
            CREATE TABLE {table_name} (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            student_id VARCHAR(50) NOT NULL,
            student_name VARCHAR(100),
            total_marks FLOAT,
            obtained_marks FLOAT,
            submitted_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
            """)
            db.session.execute(query)
            db.session.commit()
            
            socketio.emit('quiz_progress', {'percentage': 100, 'message': 'Quiz Ready!', 'status': 'completed'})

        except Exception as e:
            db.session.rollback()
            print(f"Generation Error: {e}")
            from core.models import Quiz
            try:
                Quiz.query.filter_by(id=id).delete()
                db.session.commit()
                print(f"Successfully deleted stuck quiz {id} from database.")
            except Exception as cleanup_e:
                print(f"Failed to delete stuck quiz: {cleanup_e}")

            socketio.emit('quiz_progress', {'percentage': 0, 'message': f'Error: {str(e)}', 'status': 'error'})

        finally:
            # FIX 4: Close the thread's connection to the database to prevent hanging locks
            db.session.remove()


def generate_unique_id(prefix):
    import uuid
    return f"{prefix}_{str(uuid.uuid4()).split('-')[0].upper()}"


@bp.route('/start-generation', methods=['POST'])
def start_generation():
    name = request.form.get('name')
    pdf_file = request.files.get('pdf')
    topics = request.form.get('topics')
    count = request.form.get('count')
    difficulty = request.form.get('difficulty')
    teacher = session['id']
    from core.models import Teacher
    classID = Teacher.query.filter_by(id=teacher).first().classID
    status = 'processing'
    id = generate_unique_id('QZ')
    path = None
    print(id, name, teacher, classID, pdf_file, topics, count, difficulty, status)

    if pdf_file:
        filename = secure_filename(pdf_file.filename)
        path = os.path.join(uploads_folder, filename)
        pdf_file.save(path)
    try:
        from core.models import Quiz
        pending_quiz = Quiz(
            id=id,
            name=name,
            teacher=teacher,
            class_id=classID,
            status=status,
            embedding=None
        )
        db.session.add(pending_quiz)
        db.session.commit()
    except Exception as e:
        return jsonify(success=False, message="Database error")

    from flask import current_app 
    with open(env_file, 'r') as f:
        data = f.read()
        if data == '':
            try:
                from core.models import Quiz
                Quiz.query.filter_by(id=id).delete()
                db.session.commit()
            except Exception as cleanup_e:
                print(f"Failed to delete stuck quiz: {cleanup_e}")
                return jsonify({
                "success": False, 
                "message": "No API key found. Please update your settings.",
                "redirect": url_for('zenith.home') 
            }), 400
        else:
            try:
                data = eval(data)
            except Exception as e:
                Quiz.query.filter_by(id=id).delete()
                db.session.commit()
                
                print(f"Failed to delete stuck quiz: {cleanup_e}")
                return jsonify(success=False, message="Corrupted settings file."), 500
      
    app_instance = current_app._get_current_object()
    
    thread = threading.Thread(
        target=generate_quiz, 
        args=(app_instance, id, data, name, teacher, classID, path, topics, count, difficulty, status)
    )
    thread.daemon = True #
    thread.start()
   
    return jsonify(success=True, quiz_id=id)


